namespace Daycry\Auth\Entities;

/**
 * A row of an RBAC pivot table (groups_users, permissions_users,
 * permissions_groups): timestamped, and may expire via `until_at`.
 */
abstract class PivotEntity extends Entity
{
    /**
     * @var         list<string>
     * @phpstan-var list<string>
     * @psalm-var list<string>
     */
    protected $dates = [
        'created_at',
        'updated_at',
        'deleted_at',
        'until_at',
    ];
}
